def _count_by(items: Sequence[Any], attr: str) -> dict[str, int]:
    out: dict[str, int] = {}
    for i in items:
        k = str(getattr(i, attr))
        out[k] = out.get(k, 0) + 1
    return out


def _proposal_note(proposal: DDLProposal | None, table: str) -> str:
    if proposal is None or proposal.table_name != table:
        return ""
    bits = [f"ORDER BY ({', '.join(proposal.order_by)})"]
    if proposal.partition_by:
        bits.append(f"PARTITION BY {proposal.partition_by}")
    if proposal.ttl:
        bits.append(f"TTL {proposal.ttl}")
    reason = proposal.rationale.get("order_by", "")
    if reason:
        bits.append(f"order_by rationale: {reason}")
    return "; ".join(bits)


def _proposal_entries(proposal: DDLProposal) -> list[dict[str, Any]]:
    """Turn the instrumentation agent's derived semantics into context entries.

    This is what lets the Analytics Agent read *why* a table is shaped the way it is
    from the context layer rather than from another agent's return value.
    """
    s = proposal.semantics
    slug = s.feature_slug
    entries: list[dict[str, Any]] = [
        {
            "entry_id": f"entity.{slug}.entity_key",
            "kind": "entity",
            "key": f"{slug} entity key: {s.entity_key}",
            "body": (
                f"The grain of `{s.table_fqn}` is `{s.entity_key}` "
                f"(confidence {s.entity_key_confidence:.2f}); secondary keys: "
                f"{', '.join(s.secondary_keys) or 'none'}. Derived from the spec and the raw "
                f"events by the instrumentation agent, not assumed."
            ),
            "formula": "",
            "refs": sorted({proposal.table_name, s.entity_key, *s.secondary_keys}),
            "source": "instrumentation_agent",
            "source_ref": f"DDLProposal:{proposal.table_name}",
            "status": "active",
            "confidence": float(s.entity_key_confidence),
        },
        {
            "entry_id": f"business_def.{slug}.funnel",
            "kind": "business_def",
            "key": f"{slug} funnel",
            "body": (
                f"Ordered steps on `{s.table_fqn}`: {' -> '.join(s.ordered_steps) or 'none derived'} "
                f"(step order source: {s.step_order_source}). Segment dimensions: "
                f"{', '.join(s.segment_dims) or 'none'}. Event discriminator column: "
                f"`{s.event_column}`."
            ),
            "formula": "",
            "refs": sorted({proposal.table_name, s.event_column, *s.segment_dims}),
            "source": "instrumentation_agent",
            "source_ref": f"DDLProposal:{proposal.table_name}",
            "status": "active",
            "confidence": 1.0,
        },
    ]
    if s.partial_identity_columns:
        entries.append(
            {
                "entry_id": f"gap.data_quality.{proposal.table_name}.partial_identity",
                "kind": "gap",
                "key": f"{proposal.table_name}: partial identity coverage",
                "body": (
                    f"Columns with < 100% coverage on `{proposal.table_name}`: "
                    f"{', '.join(s.partial_identity_columns)}. House rules forbid Nullable on hot "
                    f"columns, so these default to the empty string. Every distinct count over "
                    f"them MUST be uniqIf(col, col != ''); a bare uniq() would count '' as a real "
                    f"identity. Disconnected event types: "
                    f"{', '.join(s.disconnected_event_types) or 'none'}."
                ),
                "formula": "",
                "refs": sorted({proposal.table_name, *s.partial_identity_columns}),
                "source": "instrumentation_agent",
                "source_ref": f"DDLProposal:{proposal.table_name}",
                "status": "open",
                "confidence": 1.0,
            }
        )
    return entries


_KIND_ORDER = [
    "business_def",
    "entity",
    "metric",
    "relationship",
    "table_doc",
    "column_doc",
    "known_issue",
    "gap",
    "contradiction",
]


def _render_context(
    version: int,
    snapshot_id: str,
    fingerprint: str,
    entries: Sequence[ContextEntry],
    contradictions: Sequence[dict[str, Any]],
    disputed: set[str],
) -> str:
    formulas: dict[str, str] = {}
    lines = [
        f"# Atlys context layer — v{version}",
        "",
        "> **Generated file. Do not edit.** The ClickHouse tables `context_entry_log`, "
        "`context_snapshot`, `context_changelog` and `contradiction` are the source of truth; "
        "this markdown is a render of them. To change the context, write an entry.",
        "",
        f"- context version: **{version}**",
        f"- snapshot id: `{snapshot_id}`",
        f"- schema fingerprint: `{fingerprint[:32]}`",
        f"- entries: **{len(entries)}**",
        f"- contradictions recorded: **{len(contradictions)}** "
        f"({sum(1 for c in contradictions if c.get('verified'))} verified by an executed query)",
        f"- rendered at: {datetime.now().isoformat(timespec='seconds')}",
        "",
    ]
    by_kind: dict[str, list[ContextEntry]] = {}
    for e in entries:
        by_kind.setdefault(e.kind, []).append(e)
    for kind in _KIND_ORDER + sorted(set(by_kind) - set(_KIND_ORDER)):
        group = by_kind.get(kind)
        if not group:
            continue
        lines.append(f"## {kind} ({len(group)})")
        lines.append("")
        for e in sorted(group, key=lambda x: x.entry_id):
            flag = " **[DISPUTED]**" if e.entry_id in disputed else ""
            lines.append(f"### `{e.entry_id}` @v{e.version}{flag}")
            lines.append("")
            lines.append(f"**{e.key}**")
            lines.append("")
            lines.append(e.body)
            meta = [f"source: `{e.source}`", f"status: `{e.status}`", f"confidence: {e.confidence:g}"]
            if e.refs:
                meta.append("refs: " + ", ".join(f"`{r}`" for r in e.refs[:12]))
            lines.append("")
            lines.append("<sub>" + " · ".join(meta) + "</sub>")
            lines.append("")
    if contradictions:
        lines.append("## Contradictions — the LLM proposes, SQL adjudicates")
        lines.append("")
        for c in contradictions:
            mark = "✅ verified" if c.get("verified") else "⚠️ unverified"
            lines.append(f"### [{c['kind']}] {c['title']}  ({c['severity']}, {mark})")
            lines.append("")
            lines.append(f"- **Context claims:** {c['claim']}")
            lines.append(f"- **Reality says:** {c['evidence']}")
            lines.append(f"- **Proposed resolution:** {c['proposed_resolution']}")
            if c.get("entry_ids"):
                lines.append("- **Entries:** " + ", ".join(f"`{e}`" for e in c["entry_ids"]))
            if c.get("verification_sql"):
                lines.append("")
                lines.append("```sql")
                lines.append(c["verification_sql"])
                lines.append("```")
                lines.append("")
                lines.append(f"Executed result: `{c.get('verification_result', '')}`")
            lines.append("")
    return "\n".join(lines) + "\n"


def _render_changelog(
    rows: Sequence[dict[str, Any]], snapshots: Sequence[dict[str, Any]]
) -> str:
    lines = [
        "# Context layer changelog",
        "",
        "> Generated from `context_changelog` and `context_snapshot`. Every line is an "
        "append-only fact about how the context moved.",
        "",
        "## Versions",
        "",
        "| version | snapshot id | entries | schema fingerprint | note | run_id |",
        "|---|---|---|---|---|---|",
    ]
    for s in snapshots:
        lines.append(
            f"| v{s['version']} | `{s['snapshot_id']}` | {s['entry_count']} | "
            f"`{str(s.get('schema_fingerprint') or '')[:12]}` | {s.get('note', '')} | "
            f"`{str(s.get('run_id') or '')[:8]}` |"
        )
    lines += ["", "## Entry history", ""]
    current_run = object()
    for r in rows:
        if r["run_id"] != current_run:
            current_run = r["run_id"]
            lines.append("")
            lines.append(f"### run `{str(current_run)[:12] or 'n/a'}` — {r['ts']}")
            lines.append("")
        arrow = f"v{r['from_version']} → v{r['to_version']}" if r["from_version"] else f"v{r['to_version']}"
        lines.append(f"- **{r['action']}** `{r['entry_id']}` ({arrow}) — {r['summary']}")
        if r.get("detail"):
            lines.append(f"  - {r['detail']}")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------
# module-level API (the signatures the pipeline codes against)
# --------------------------------------------------------------------------


def bootstrap(base_context_md: str | Path = DEFAULT_BASE_CONTEXT, ch: Any = None, run_id: str = "") -> int:
    ch = ch or _default_ch()
    return ContextAgent(ch, run_id=run_id).bootstrap(base_context_md)


def snapshot(ch: Any = None, run_id: str = "", note: str = "") -> ContextSnapshot:
    ch = ch or _default_ch()
    return ContextAgent(ch, run_id=run_id).snapshot(note=note)


def reconcile(
    ch: Any = None,
    new_tables: Sequence[str] = (),
    proposal: DDLProposal | None = None,
    run_id: str = "",
    note: str = "",
    use_llm: bool = False,
) -> ContextDiff:
    ch = ch or _default_ch()
    return ContextAgent(ch, run_id=run_id).reconcile(
        new_tables, proposal, note=note, use_llm=use_llm
    )


def render_markdown(ch: Any = None, out_dir: str | Path = DEFAULT_OUT_DIR, run_id: str = "") -> dict[str, Path]:
    ch = ch or _default_ch()
    return ContextAgent(ch, run_id=run_id).render_markdown(out_dir)


def _default_ch() -> Any:
    from ch import CH

    return CH()
